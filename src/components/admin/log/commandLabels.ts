/** Lesbare Bezeichnung eines Befehlstyps (unbekannte Typen bleiben als Code stehen) */
export function commandLabel(type: string): string {
  return (COMMAND_LABELS as Record<string, string>)[type] ?? SERVER_LABELS[type] ?? type;
}

/** Revisionen, die die Serverschicht ohne Command anlegt (Sandbox, Vorlagen; NTH2 2.1/2.6) */
const SERVER_LABELS: Record<string, string> = {
  SANDBOX_CREATE: 'Sandbox angelegt',
  SANDBOX_APPLY: 'Sandbox übernommen',
};

/** Zusammenfassung ohne Override-Präfix; reiner Befehlscode wird zur lesbaren Bezeichnung */
export function readableSummary(summary: string, type: string): { text: string; isCode: boolean } {
  const s = summary.replace(/^⚠\s*/, '');
  if (s === type || /^[A-Z][A-Z0-9_]+$/.test(s)) return { text: commandLabel(s), isCode: true };
  return { text: s, isCode: false };
}
